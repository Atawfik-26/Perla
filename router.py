    # =====================================================
    # MATCHER
    # =====================================================

    @staticmethod
    def _contains_any(
        message,
        patterns
    ):

        for pattern in patterns:

            try:

                if re.search(
                    pattern,
                    message,
                    re.IGNORECASE
                ):
                    return True

            except re.error:

                if pattern in message:
                    return True

        return False


